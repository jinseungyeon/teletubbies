// Generate the DB catalogue from the FE's actual code-drawn character definitions.
// Run from repo root: node be/sync_character_catalog.mjs (Node >= 20).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { HAIR_STYLES, HAIR_COLORS, EYE_COLORS, OUTFITS, OUTFIT_COLORS,
  OUTFIT_PALETTES, SKINS, GENDERS } from '../fe/src/character.js';

const items = [];
const add = (category, id, label, index, extra = {}) => items.push({
  category_id: category, item_id: id, label, sort_order: index,
  metadata: { frontend_index: index, catalog_source: 'fe/src/character.js', ...extra },
});
HAIR_STYLES.forEach((v,i)=>add('hair_style',v.key,v.name,i));
HAIR_COLORS.forEach((v,i)=>add('hair_color',v.hex,v.name,i,{hex:v.hex}));
EYE_COLORS.forEach((v,i)=>add('eye_color',v.hex,v.name,i,{hex:v.hex}));
OUTFITS.forEach((v,i)=>add('outfit',v.key,v.name,i));
OUTFIT_COLORS.forEach((hex,i)=>add('outfit_color',hex,`${OUTFIT_PALETTES[Math.floor(i/4)].name} ${i%4+1}`,i,{hex}));
SKINS.forEach((v,i)=>add('special_skin',v.key,v.name,i,{hex:v.hex}));
Object.entries(GENDERS).forEach(([id,label],i)=>add('gender',id,label,i));
if(new Set(items.map(x=>`${x.category_id}/${x.item_id}`)).size!==items.length)throw Error('Duplicate item ID');
const quote = s => `'${String(s).replaceAll("'","''")}'`;
const tuples=items.map(x=>`(${quote(x.category_id)},${quote(x.item_id)},${quote(x.label)},${quote(JSON.stringify(x.metadata))}::jsonb,${x.sort_order})`);
const keep=items.map(x=>`(${quote(x.category_id)},${quote(x.item_id)})`).join(',');
const sql=`-- Generated by be/sync_character_catalog.mjs from the actual FE definitions.
-- Apply AFTER 004 as postgres. Code-drawn SVG assets live in fe/src/character.js.
-- Re-running refreshes this catalogue only. It does not recreate companies/users/seats.
BEGIN;
INSERT INTO public.avatar_items(category_id,item_id,label,metadata,sort_order)
VALUES
  ${tuples.join(',\n  ')}
ON CONFLICT(category_id,item_id) DO UPDATE SET label=EXCLUDED.label,
  metadata=EXCLUDED.metadata,sort_order=EXCLUDED.sort_order,enabled=true;
UPDATE public.avatar_items SET enabled=false
WHERE metadata->>'catalog_source'='fe/src/character.js'
  AND (category_id,item_id) NOT IN (${keep});
NOTIFY pgrst, 'reload schema';
COMMIT;
`;
writeFileSync(new URL('./005_avatar_catalog.sql',import.meta.url),sql);
writeFileSync(new URL('./avatar_catalog.json',import.meta.url),JSON.stringify(items,null,2)+'\n');
console.log(`Generated ${items.length} real avatar catalogue entries at ${fileURLToPath(new URL('.',import.meta.url))}`);
